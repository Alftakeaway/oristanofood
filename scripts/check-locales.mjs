import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const base='src/i18n';
const dictionary=JSON.parse(fs.readFileSync(`${base}/en-GB.json`,'utf8'));
assert.ok(Object.keys(dictionary).length>100);
for(const [key,value] of Object.entries(dictionary))assert.ok(key.trim()&&typeof value==='string'&&value.trim(),`Empty translation: ${key}`);
const code=ts.transpileModule(fs.readFileSync(`${base}/copy.ts`,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,esModuleInterop:true}}).outputText;
const context={exports:{},require(name){assert.equal(name,'./en-GB.json');return dictionary;}};
vm.runInNewContext(code,context);
const t=context.exports.translate;
assert.equal(t('Pane di semola','it'),'Pane di semola');
assert.equal(t('Pane di semola','en-GB'),'Semolina bread');
assert.equal(t('1.234,50 €','en-GB'),'€1234.50');
assert.equal(t('glutine, latte, uova','en-GB'),'gluten, milk, eggs');
assert.equal(t('Custom business name','en-GB'),'Custom business name');
assert.equal(t('Chiuso · apre 19:00','en-GB'),'Closed · opens 19:00');
assert.equal(t('• 2 × Pane di semola — 7,00 €','en-GB'),'• 2 × Semolina bread — €7.00');
assert.equal(t('Ciao! Vorrei prenotare un tavolo.\nPersone: 2','en-GB'),'Hello! I would like to book a table.\nGuests: 2');
assert.equal(t('Ciao Pizzeria La Brace! Vorrei prenotare un tavolo.\n— Nome: Demo Guest','en-GB'),'Hello Pizzeria La Brace! I would like to book a table.\n— Name: Demo Guest');
console.log(`English UK: ${Object.keys(dictionary).length} translations; currency, allergens, fallback and enquiry interpolation verified.`);
