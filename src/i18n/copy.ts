import dictionary from "./en-GB.json";
export type Locale = "it" | "en-GB";
const normalise = (text: string) => text.replace(/&(?:apos|#39);/g, "'").replace(/&amp;/g,"&").replace(/[’‘]/g,"'").replace(/\s+/g," ").trim();
const entries = new Map(Object.entries(dictionary).map(([key,value]) => [normalise(key),value]));
const lower = new Map([...entries].map(([key,value]) => [key.toLocaleLowerCase('it'),value]));
export function translate(text: string, locale: Locale): string {
 if(locale === "it" || !text.trim()) return text;
 const key = normalise(text);
 const exact = entries.get(key) ?? lower.get(key.toLocaleLowerCase('it'));
 if(exact) return `${/^\s/.test(text) ? ' ' : ''}${exact}${/\s$/.test(text) ? ' ' : ''}`;
 if(text.includes('\n')) return text.split('\n').map(line=>translate(line,locale)).join('\n');
 const greeting=/^Ciao (.+)! Vorrei prenotare un tavolo\.$/.exec(key);if(greeting)return `Hello ${greeting[1]}! I would like to book a table.`;
 const label=/^([—-]\s*)?(Nome|Totale|Ritiro|Data|Ora|Persone|Note|Allergeni dichiarati|Categoria):\s*(.*)$/.exec(key);
 if(label) return `${label[1] || ''}${translate(label[2] ?? '',locale)}: ${translate(label[3] ?? '',locale)}`;
 const row=/^(•\s*)?(\d+)\s*[×x]\s*(.+?)\s[—-]\s(.+)$/.exec(key);
 if(row) return `${row[1] || ''}${row[2]} × ${translate(row[3] ?? '',locale)} — ${translate(row[4] ?? '',locale)}`;
 const plural=/^(\d+) prodotti$/.exec(key);if(plural)return `${plural[1]} products`;
 const basket=/^Aggiungi (.+) al cestino$/.exec(key);if(basket)return `Add ${translate(basket[1] || '',locale)} to basket`;
 const detail=/^Apri la scheda di (.+)$/.exec(key);if(detail)return `View ${translate(detail[1] || '',locale)} details`;
 const quantity=/^(Riduci quantità di|Aumenta quantità di|Riduci|Aumenta) (.+)$/.exec(key);if(quantity)return `${quantity[1]?.startsWith('Riduci')?'Reduce':'Increase'} ${quantity[1]?.includes('quantità')?'quantity of ':''}${translate(quantity[2] || '',locale)}`;
 const dishCount=/^(\d+) piatti$/.exec(key);if(dishCount)return `${dishCount[1]} dishes`;
 const action=/^(Aggiungi|Riduci quantità di|Aumenta quantità di|Foto di) (.+?)( all'ordine)?$/.exec(key);
 if(action) return `${({'Aggiungi':'Add','Riduci quantità di':'Reduce quantity of','Aumenta quantità di':'Increase quantity of','Foto di':'Photograph of'} as Record<string,string>)[action[1] ?? ''] || action[1]} ${translate(action[2] ?? '',locale)}${action[3]?' to order':''}`;
 const date=/^(Lunedì|Martedì|Mercoledì|Giovedì|Venerdì|Sabato|Domenica) (\d{1,2}) ([a-zà-ÿ]+)(.*)$/.exec(key);
 if(date) return `${translate(date[1] || '',locale)} ${date[2]} ${translate(date[3] || '',locale)}${date[4] || ''}`;
 const status=/^(Aperto|Chiuso|Chiusi)(.*)$/.exec(key);
 if(status) return `${status[1]==='Aperto'?'Open':'Closed'}${(status[2] || '').replace('fino alle','until').replace('apre','opens').replace('domani','tomorrow')}`;
 const stage=/^La lavorazione, in (\d+) passaggi$/.exec(key);if(stage)return `The craft, in ${stage[1]} stages`;
 const slide=/^Passaggio (\d+) di (\d+):$/.exec(key);if(slide)return `Stage ${slide[1]} of ${slide[2]}:`;
 const count = /^(?:Apri il cestino,|Apri il carrello,) (\d+) prodotti$/.exec(key);
 if(count) return `Open basket, ${count[1]} items`;
 const added = /^(.*) aggiunto al cestino\.$/.exec(key);
 if(added) return `${translate(added[1] ?? "",locale)} added to your basket.`;
 const pdfMoney=/^(\d[\d.]*(?:,\d{2})?) EUR$/.exec(key);if(pdfMoney)return `${(pdfMoney[1] || '').includes(',') ? (pdfMoney[1] || '').replace(/\./g,'').replace(',','.') : (pdfMoney[1] || '')} EUR`;
 const money = /^(\d[\d.]*(?:,\d{2})?)\s*€$/.exec(key);
 if(money) return `€${(money[1] ?? '').replace(/\./g,'').replace(',','.')}`;
 if(key.includes(', ')) return key.split(', ').map(part => entries.get(normalise(part)) ?? lower.get(normalise(part).toLowerCase()) ?? part).join(', ');
 return text;
}
